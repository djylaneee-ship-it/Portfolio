let LANG = (() => {
  try { const l = localStorage.getItem('rdh-lang'); if (I18N[l]) return l; } catch {}
  return 'en';
})();

const locale = () => LOCALES[LANG] || 'en-US';
const has = (key) => key in I18N[LANG] || key in I18N.en;

function t(key, vars = {}) {
  const d = I18N[LANG];
  const one = vars.n === 1 ? key + '_one' : null;
  const s = (one && (d[one] ?? I18N.en[one])) ?? d[key] ?? I18N.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, v) => vars[v] ?? '');
}

// Textes de la page HTML : data-i18n (texte), data-i18n-ph (placeholder), data-i18n-title.
function applyStatic() {
  document.documentElement.lang = LANG;
  for (const el of document.querySelectorAll('[data-i18n]')) el.innerHTML = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
  for (const el of document.querySelectorAll('[data-i18n-title]')) el.setAttribute('aria-label', t(el.dataset.i18nTitle));
  const ls = document.getElementById('login-lang');
  if (ls) ls.value = LANG;
}
